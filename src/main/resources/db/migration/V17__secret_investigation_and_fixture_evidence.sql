-- Worker completion and approved internal policy commands may invoke this idempotent projection.
CREATE FUNCTION secret_reconcile_test_alerts(target_run BIGINT DEFAULT NULL) RETURNS BIGINT LANGUAGE plpgsql AS $$
DECLARE k RECORD; loc RECORD; current_alert BIGINT; previous_alert BIGINT; linked_case BIGINT;
 task BIGINT; desired VARCHAR(30); seen TIMESTAMPTZ; first_location BIGINT; changed BIGINT; affected BIGINT:=0;
BEGIN
 FOR k IN SELECT DISTINCT fs.credential_set_id FROM secret_test_fixture_status fs
   WHERE fs.fixture_status IN ('POSSIBLE_REAL','CONFIRMED_REAL') AND (target_run IS NULL OR EXISTS(
     SELECT 1 FROM secret_current_valid_findings f WHERE f.occurrence_id=fs.occurrence_id AND f.run_id=target_run))
   ORDER BY fs.credential_set_id
 LOOP
  PERFORM 1 FROM secret_credential_sets WHERE credential_set_id=k.credential_set_id FOR UPDATE;
  SELECT CASE WHEN bool_or(fs.fixture_status='CONFIRMED_REAL') THEN 'CONFIRMED_REAL' ELSE 'SUSPECTED_REAL' END,
         max(f.detected_at),min(fs.occurrence_id)
  INTO desired,seen,first_location FROM secret_test_fixture_status fs
  JOIN secret_current_valid_findings f ON f.occurrence_id=fs.occurrence_id
  WHERE fs.credential_set_id=k.credential_set_id AND fs.fixture_status IN ('POSSIBLE_REAL','CONFIRMED_REAL');
  IF first_location IS NULL THEN CONTINUE; END IF;
  SELECT alert_id INTO current_alert FROM secret_cross_environment_alerts
   WHERE credential_set_id=k.credential_set_id AND closed_at IS NULL FOR UPDATE;
  IF current_alert IS NULL THEN
   SELECT case_id INTO linked_case FROM secret_response_cases WHERE credential_set_id=k.credential_set_id
    AND case_origin='TEST' AND is_current AND action_status<>'RESOLVED' ORDER BY case_id DESC LIMIT 1;
   task:=NULL;
   IF linked_case IS NULL THEN
    INSERT INTO secret_investigation_tasks(target_type,occurrence_id,missing_reason_code,creation_source)
     VALUES('OCCURRENCE',first_location,'FIXTURE_UNCONFIRMED','AUTO_TEST_ALERT') ON CONFLICT DO NOTHING RETURNING task_id INTO task;
    IF task IS NULL THEN SELECT task_id INTO task FROM secret_investigation_tasks
      WHERE occurrence_id=first_location AND missing_reason_code='FIXTURE_UNCONFIRMED' AND status='OPEN';
    ELSE INSERT INTO secret_investigation_history(task_id,event_type,safe_changes,task_version)
      VALUES(task,'AUTO_CREATED','{"creationSource":"AUTO_TEST_ALERT"}',0); END IF;
   END IF;
   SELECT alert_id INTO previous_alert FROM secret_cross_environment_alerts
    WHERE credential_set_id=k.credential_set_id AND closed_at IS NOT NULL ORDER BY alert_id DESC LIMIT 1;
   INSERT INTO secret_cross_environment_alerts(credential_set_id,previous_alert_id,status,test_case_id,investigation_task_id,
      first_observed_at,last_observed_at)
    VALUES(k.credential_set_id,previous_alert,desired,linked_case,task,seen,seen) RETURNING alert_id INTO current_alert;
   INSERT INTO secret_cross_environment_alert_history(alert_id,event_type,safe_changes,alert_version)
    VALUES(current_alert,'AUTO_CREATED',jsonb_build_object('status',desired),0);
   affected:=affected+1;
  ELSE
   UPDATE secret_cross_environment_alerts SET status=CASE WHEN desired='CONFIRMED_REAL' THEN desired ELSE status END,
      last_observed_at=GREATEST(last_observed_at,seen),version=version+1
    WHERE alert_id=current_alert AND (last_observed_at<seen OR status='SUSPECTED_REAL' AND desired='CONFIRMED_REAL');
   GET DIAGNOSTICS changed=ROW_COUNT;
   IF changed>0 THEN
    INSERT INTO secret_cross_environment_alert_history(alert_id,event_type,safe_changes,alert_version)
     SELECT alert_id,CASE WHEN desired='CONFIRMED_REAL' THEN 'REAL_CONFIRMED' ELSE 'OBSERVED' END,
       jsonb_build_object('status',status),version FROM secret_cross_environment_alerts WHERE alert_id=current_alert;
   END IF;
  END IF;
  FOR loc IN SELECT fs.occurrence_id,max(f.detected_at) AS observed_at FROM secret_test_fixture_status fs
   JOIN secret_current_valid_findings f ON f.occurrence_id=fs.occurrence_id
   WHERE fs.credential_set_id=k.credential_set_id AND fs.fixture_status IN ('POSSIBLE_REAL','CONFIRMED_REAL') GROUP BY fs.occurrence_id
  LOOP
   INSERT INTO secret_cross_environment_alert_locations(alert_id,occurrence_id,first_observed_at,last_observed_at)
    VALUES(current_alert,loc.occurrence_id,loc.observed_at,loc.observed_at)
    ON CONFLICT(alert_id,occurrence_id) DO UPDATE SET last_observed_at=GREATEST(secret_cross_environment_alert_locations.last_observed_at,EXCLUDED.last_observed_at);
  END LOOP;
 END LOOP;
 RETURN affected;
END $$;

-- An approved manifest/version and its protected identities are immutable; revocation remains explicit.
CREATE FUNCTION secret_guard_fixture_manifest() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN
 IF TG_OP='INSERT' AND NEW.approval_status<>'DRAFT' THEN RAISE EXCEPTION 'FIXTURE_DRAFT_REQUIRED'; END IF;
 IF TG_OP='UPDATE' AND OLD.approval_status='REVOKED' AND to_jsonb(NEW)<>to_jsonb(OLD) THEN RAISE EXCEPTION 'FIXTURE_VERSION_IMMUTABLE'; END IF;
 IF TG_OP='UPDATE' AND OLD.approval_status<>'DRAFT' THEN
  IF NEW.approval_status<>'REVOKED' OR NEW.revoked_at IS NULL OR
     (to_jsonb(NEW)-ARRAY['approval_status','revoked_at'])<>(to_jsonb(OLD)-ARRAY['approval_status','revoked_at']) THEN
   RAISE EXCEPTION 'FIXTURE_VERSION_IMMUTABLE'; END IF;
 END IF;
 IF NEW.approval_status='APPROVED' THEN
  IF NOT EXISTS(SELECT 1 FROM secret_fixture_manifest_identities i WHERE i.manifest_id=NEW.manifest_id AND i.manifest_version=NEW.version)
   OR EXISTS(SELECT 1 FROM secret_fixture_manifest_identities i JOIN secret_connection_scopes s ON s.scope_id=i.scope_id
    WHERE i.manifest_id=NEW.manifest_id AND i.manifest_version=NEW.version AND
     (NOT s.enabled OR s.response_origin<>'TEST' OR s.revision<>i.scope_revision OR NOT EXISTS(
       SELECT 1 FROM secret_role_grants g WHERE g.user_id=NEW.approved_by_user_id AND g.role='SECURITY' AND g.revoked_at IS NULL
        AND (g.connection_id IS NULL OR g.connection_id=s.connection_id)))) THEN RAISE EXCEPTION 'FIXTURE_APPROVAL_INVALID'; END IF;
 END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER secret_guard_fixture_manifest BEFORE INSERT OR UPDATE ON secret_fixture_manifests FOR EACH ROW EXECUTE FUNCTION secret_guard_fixture_manifest();
CREATE FUNCTION secret_guard_fixture_identity() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE mid BIGINT; ver BIGINT; BEGIN
 IF TG_OP='UPDATE' AND EXISTS(SELECT 1 FROM secret_fixture_manifests WHERE manifest_id=OLD.manifest_id AND version=OLD.manifest_version AND approval_status<>'DRAFT') THEN RAISE EXCEPTION 'FIXTURE_VERSION_IMMUTABLE'; END IF;
 mid:=CASE WHEN TG_OP='DELETE' THEN OLD.manifest_id ELSE NEW.manifest_id END;
 ver:=CASE WHEN TG_OP='DELETE' THEN OLD.manifest_version ELSE NEW.manifest_version END;
 IF EXISTS(SELECT 1 FROM secret_fixture_manifests WHERE manifest_id=mid AND version=ver AND approval_status<>'DRAFT') THEN RAISE EXCEPTION 'FIXTURE_VERSION_IMMUTABLE'; END IF;
 IF TG_OP='DELETE' THEN RETURN OLD; END IF; RETURN NEW;
END $$;
CREATE TRIGGER secret_guard_fixture_identity BEFORE INSERT OR UPDATE OR DELETE ON secret_fixture_manifest_identities FOR EACH ROW EXECUTE FUNCTION secret_guard_fixture_identity();
