-- Investigation and trusted synthetic-fixture evidence. No raw value or source context is stored.
CREATE TABLE secret_investigation_tasks (
 task_id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
 target_type VARCHAR(20) NOT NULL CHECK(target_type IN ('OCCURRENCE','SCOPE')),
 occurrence_id BIGINT REFERENCES secret_occurrences,
 scope_id BIGINT REFERENCES secret_connection_scopes,
 missing_reason_code VARCHAR(80) NOT NULL,
 creation_source VARCHAR(30) NOT NULL CHECK(creation_source IN ('HUMAN_MORE_INFO','AUTO_TEST_ALERT','SCOPE_RESTORE')),
 assignee_user_id BIGINT REFERENCES dashboard_users,
 due_at TIMESTAMPTZ,
 status VARCHAR(20) NOT NULL DEFAULT 'OPEN' CHECK(status IN ('OPEN','CLOSED')),
 human_follow_up_required BOOLEAN NOT NULL DEFAULT false,
 evidence_ref VARCHAR(120), version BIGINT NOT NULL DEFAULT 0 CHECK(version>=0),
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP, closed_at TIMESTAMPTZ,
 resolving_decision_id BIGINT REFERENCES secret_exposure_assessments(assessment_id),
 restored_run_scope_id BIGINT REFERENCES secret_run_scopes,
 CHECK((target_type='OCCURRENCE' AND occurrence_id IS NOT NULL AND scope_id IS NULL)
    OR (target_type='SCOPE' AND occurrence_id IS NULL AND scope_id IS NOT NULL)),
 CHECK((creation_source<>'HUMAN_MORE_INFO' AND NOT human_follow_up_required) OR (assignee_user_id IS NOT NULL AND due_at IS NOT NULL)),
 CHECK((status='OPEN' AND closed_at IS NULL) OR (status='CLOSED' AND closed_at IS NOT NULL
    AND ((resolving_decision_id IS NOT NULL)::int+(restored_run_scope_id IS NOT NULL)::int)=1))
);
CREATE UNIQUE INDEX uq_secret_open_occurrence_investigation ON secret_investigation_tasks(occurrence_id,missing_reason_code) WHERE status='OPEN' AND target_type='OCCURRENCE';
CREATE UNIQUE INDEX uq_secret_open_scope_investigation ON secret_investigation_tasks(scope_id,missing_reason_code) WHERE status='OPEN' AND target_type='SCOPE';
CREATE INDEX idx_secret_investigation_owner_due ON secret_investigation_tasks(assignee_user_id,due_at,task_id) WHERE status='OPEN';
CREATE TABLE secret_investigation_history (
 history_id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY, task_id BIGINT NOT NULL REFERENCES secret_investigation_tasks,
 event_type VARCHAR(40) NOT NULL, actor_user_id BIGINT REFERENCES dashboard_users,
 safe_changes JSONB NOT NULL DEFAULT '{}'::jsonb CHECK(jsonb_typeof(safe_changes)='object'), evidence_ref VARCHAR(120),
 task_version BIGINT NOT NULL, created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE secret_fixture_manifests (
 manifest_id BIGINT GENERATED BY DEFAULT AS IDENTITY, version BIGINT NOT NULL CHECK(version>0),
 protected_manifest_ref VARCHAR(300) NOT NULL, approval_status VARCHAR(20) NOT NULL CHECK(approval_status IN ('DRAFT','APPROVED','REVOKED')),
 approved_by_user_id BIGINT REFERENCES dashboard_users, valid_from TIMESTAMPTZ NOT NULL, valid_until TIMESTAMPTZ,
 revoked_at TIMESTAMPTZ, allow_auto_attestation BOOLEAN NOT NULL DEFAULT false,
 PRIMARY KEY(manifest_id,version), CHECK(valid_until IS NULL OR valid_until>valid_from),
 CHECK(approval_status<>'APPROVED' OR approved_by_user_id IS NOT NULL)
);
-- Internal-only HMAC identities. Never selected by a dashboard response or sent to an AI provider.
CREATE TABLE secret_fixture_manifest_identities (
 identity_id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY, manifest_id BIGINT NOT NULL, manifest_version BIGINT NOT NULL,
 scope_id BIGINT NOT NULL REFERENCES secret_connection_scopes, scope_revision BIGINT NOT NULL,
 issuer VARCHAR(40) NOT NULL, credential_type VARCHAR(80) NOT NULL, fingerprint_key_version VARCHAR(40) NOT NULL,
 protected_fingerprint BYTEA NOT NULL CHECK(octet_length(protected_fingerprint)=32),
 FOREIGN KEY(manifest_id,manifest_version) REFERENCES secret_fixture_manifests(manifest_id,version),
 UNIQUE(manifest_id,manifest_version,scope_id,scope_revision,issuer,credential_type,fingerprint_key_version,protected_fingerprint)
);
CREATE TABLE secret_fixture_match_evidence (
 match_evidence_id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
 credential_set_id BIGINT NOT NULL REFERENCES secret_credential_sets, scope_id BIGINT NOT NULL REFERENCES secret_connection_scopes,
 scope_revision BIGINT NOT NULL, manifest_id BIGINT NOT NULL, manifest_version BIGINT NOT NULL,
 run_scope_id BIGINT NOT NULL REFERENCES secret_run_scopes,
 comparator_id VARCHAR(120) NOT NULL, comparator_version VARCHAR(80) NOT NULL,
 match_result VARCHAR(20) NOT NULL CHECK(match_result IN ('MATCH','NO_MATCH','UNAVAILABLE')),
 protected_match_ref VARCHAR(300), observed_at TIMESTAMPTZ NOT NULL,
 FOREIGN KEY(manifest_id,manifest_version) REFERENCES secret_fixture_manifests(manifest_id,version),
 UNIQUE(credential_set_id,scope_id,scope_revision,manifest_id,manifest_version,run_scope_id)
);
CREATE TABLE secret_test_fixture_attestations (
 attestation_id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
 credential_set_id BIGINT NOT NULL REFERENCES secret_credential_sets, scope_id BIGINT NOT NULL REFERENCES secret_connection_scopes,
 scope_revision BIGINT NOT NULL, manifest_id BIGINT NOT NULL, manifest_version BIGINT NOT NULL,
 match_evidence_id BIGINT NOT NULL UNIQUE REFERENCES secret_fixture_match_evidence,
 confirmed_by_user_id BIGINT REFERENCES dashboard_users, confirmation_source VARCHAR(20) NOT NULL CHECK(confirmation_source IN ('HUMAN','APPROVED_POLICY')),
 status VARCHAR(20) NOT NULL CHECK(status IN ('ACTIVE','REVOKED')), confirmed_at TIMESTAMPTZ NOT NULL, revoked_at TIMESTAMPTZ,
 FOREIGN KEY(manifest_id,manifest_version) REFERENCES secret_fixture_manifests(manifest_id,version),
 CHECK(confirmation_source<>'HUMAN' OR confirmed_by_user_id IS NOT NULL)
);

CREATE TABLE secret_cross_environment_alerts (
 alert_id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY, credential_set_id BIGINT NOT NULL REFERENCES secret_credential_sets,
 previous_alert_id BIGINT REFERENCES secret_cross_environment_alerts,
 status VARCHAR(30) NOT NULL CHECK(status IN ('SUSPECTED_REAL','CONFIRMED_REAL','CLOSED')),
 assignee_user_id BIGINT REFERENCES dashboard_users, due_at TIMESTAMPTZ,
 test_case_id BIGINT REFERENCES secret_response_cases, investigation_task_id BIGINT REFERENCES secret_investigation_tasks,
 version BIGINT NOT NULL DEFAULT 0, first_observed_at TIMESTAMPTZ NOT NULL, last_observed_at TIMESTAMPTZ NOT NULL,
 acknowledged_at TIMESTAMPTZ, closed_at TIMESTAMPTZ, closure_evidence_snapshot JSONB,
 CHECK(test_case_id IS NOT NULL OR investigation_task_id IS NOT NULL),
 CHECK((status='CLOSED')=(closed_at IS NOT NULL))
);
CREATE UNIQUE INDEX uq_secret_open_cross_alert ON secret_cross_environment_alerts(credential_set_id) WHERE closed_at IS NULL;
CREATE TABLE secret_cross_environment_alert_locations (
 alert_id BIGINT NOT NULL REFERENCES secret_cross_environment_alerts, occurrence_id BIGINT NOT NULL REFERENCES secret_occurrences,
 first_observed_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP, last_observed_at TIMESTAMPTZ NOT NULL, PRIMARY KEY(alert_id,occurrence_id)
);
CREATE TABLE secret_cross_environment_alert_history (
 history_id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY, alert_id BIGINT NOT NULL REFERENCES secret_cross_environment_alerts,
 event_type VARCHAR(40) NOT NULL, actor_user_id BIGINT REFERENCES dashboard_users,
 safe_changes JSONB NOT NULL DEFAULT '{}'::jsonb CHECK(jsonb_typeof(safe_changes)='object'),
 alert_version BIGINT NOT NULL, created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- The decision migration extends this shared view with current false-positive corrections.
CREATE VIEW secret_current_valid_findings AS
SELECT f.finding_id,f.occurrence_id,f.run_id,f.rule_id,f.rule_version,f.detected_at
FROM secret_findings f JOIN secret_occurrences o ON o.occurrence_id=f.occurrence_id
JOIN secret_connection_scopes s ON s.scope_id=o.scope_id
WHERE o.presence_status='PRESENT' AND s.enabled AND o.last_seen_run_id=f.run_id
 AND f.run_id=(SELECT so.run_id FROM secret_scope_outcomes so
   WHERE so.scope_id=o.scope_id AND so.scope_revision=s.revision AND so.scope_outcome='SUCCEEDED' AND so.job_status='SUCCEEDED'
   ORDER BY so.finished_at DESC NULLS LAST,so.run_id DESC LIMIT 1);

CREATE VIEW secret_confirmed_real_credentials AS
SELECT DISTINCT credential_set_id FROM secret_validation_attempts
WHERE result='VALID' AND reason_code='AUTHENTICATED' AND provider_checked_at IS NOT NULL
 AND validator_id='AWS_STS_GET_CALLER_IDENTITY' AND endpoint_class='AWS_STS';

CREATE VIEW secret_current_fixture_attestations AS
SELECT a.* FROM secret_test_fixture_attestations a
JOIN secret_fixture_manifests m ON m.manifest_id=a.manifest_id AND m.version=a.manifest_version
JOIN secret_fixture_match_evidence e ON e.match_evidence_id=a.match_evidence_id
JOIN secret_connection_scopes s ON s.scope_id=a.scope_id
JOIN secret_credential_sets c ON c.credential_set_id=a.credential_set_id
WHERE a.status='ACTIVE' AND a.revoked_at IS NULL AND m.approval_status='APPROVED' AND m.revoked_at IS NULL
 AND m.valid_from<=CURRENT_TIMESTAMP AND (m.valid_until IS NULL OR m.valid_until>CURRENT_TIMESTAMP)
 AND s.enabled AND s.response_origin='TEST' AND s.revision=a.scope_revision AND c.component_state='CONFIRMED'
 AND e.match_result='MATCH' AND e.comparator_id='LOGSSEY_PROTECTED_IDENTITY' AND e.comparator_version='1'
 AND e.credential_set_id=a.credential_set_id AND e.scope_id=a.scope_id AND e.scope_revision=a.scope_revision
 AND e.manifest_id=a.manifest_id AND e.manifest_version=a.manifest_version
 AND NOT EXISTS(SELECT 1 FROM secret_confirmed_real_credentials real WHERE real.credential_set_id=c.credential_set_id)
 AND EXISTS(SELECT 1 FROM secret_fixture_manifest_identities i WHERE i.manifest_id=a.manifest_id AND i.manifest_version=a.manifest_version
  AND i.scope_id=a.scope_id AND i.scope_revision=a.scope_revision AND i.issuer=c.issuer AND i.credential_type=c.credential_type
  AND i.fingerprint_key_version=c.fingerprint_key_version AND i.protected_fingerprint=c.fingerprint);

CREATE VIEW secret_test_fixture_status AS
SELECT o.occurrence_id,o.credential_set_id,o.scope_id,
 CASE WHEN s.response_origin<>'TEST' OR c.component_state<>'CONFIRMED'
       OR NOT EXISTS(SELECT 1 FROM secret_current_valid_findings f WHERE f.occurrence_id=o.occurrence_id) THEN 'NOT_APPLICABLE'
      WHEN EXISTS(SELECT 1 FROM secret_confirmed_real_credentials real WHERE real.credential_set_id=c.credential_set_id) THEN 'CONFIRMED_REAL'
      WHEN EXISTS(SELECT 1 FROM secret_current_fixture_attestations a WHERE a.credential_set_id=c.credential_set_id AND a.scope_id=o.scope_id) THEN 'VERIFIED_SYNTHETIC'
      ELSE 'POSSIBLE_REAL' END AS fixture_status
FROM secret_occurrences o JOIN secret_connection_scopes s ON s.scope_id=o.scope_id
JOIN secret_credential_sets c ON c.credential_set_id=o.credential_set_id;

